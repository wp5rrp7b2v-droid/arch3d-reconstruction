"""Validate scope, local resources, derivative lineage, and original identities."""
from pathlib import Path
from html.parser import HTMLParser
import json, hashlib, urllib.parse, subprocess
from PIL import Image
from v002_specs import S
ROOT=Path(__file__).resolve().parents[2];OUT=ROOT/'docs/component_atlas_v001'
BASE='e4109b3b78c503880458c820b755313f6ef90dbe'
class Links(HTMLParser):
    def __init__(self):super().__init__();self.links=[];self.imgs=[];self.ids=set()
    def handle_starttag(self,tag,attrs):
        d=dict(attrs)
        if d.get('id'):self.ids.add(d['id'])
        for key in ['href','src','data-clear']:
            if d.get(key):self.links.append(d[key])
        if tag=='img':self.imgs.append(d)
def main():
    data=json.loads((OUT/'atlas_data.json').read_text());coverage=json.loads((OUT/'assets/v002/PAGE_COVERAGE.json').read_text())
    assert len(data)==len(coverage)==79
    assert {d['id'] for d in data}==set(S)=={d['id'] for d in coverage}
    pages=[OUT/'index.html']+[OUT/'pages'/f'{d["id"]}.html' for d in data]
    parsed={p:Links() for p in pages}
    for path,parser in parsed.items():parser.feed(path.read_text())
    missing=[];checked=0;imgs=set()
    for path,parser in parsed.items():
        for link in parser.links:
            u=urllib.parse.urlsplit(link)
            if u.scheme or u.netloc:continue
            target=(path.parent/urllib.parse.unquote(u.path)).resolve() if u.path else path
            if not target.exists():missing.append(str(target))
            if u.fragment and target.suffix=='.html' and target in parsed:
                assert u.fragment in parsed[target].ids,(path,link)
            checked+=1
        for im in parser.imgs:
            assert im.get('alt'),path
            imgs.add((path.parent/im['src']).resolve())
    # qa/index.html is generated by browser QA later; it must not be silently
    # waived in final validation. The first phase explicitly declares it pending.
    pending_qa=[str(OUT/'qa/index.html')]
    missing=[m for m in missing if m not in pending_qa]
    assert not missing,missing
    for p in imgs:
        with Image.open(p) as im:im.verify()
    deriv=json.loads((OUT/'assets/v002/DERIVATION_PROVENANCE.json').read_text())
    originals=set()
    for d in deriv:
        raw=OUT/d['source'];assert hashlib.sha256(raw.read_bytes()).hexdigest()==d['source_sha256'],raw
        assert hashlib.sha256((OUT/d['file']).read_bytes()).hexdigest()==d['sha256'],d['file']
        originals.add(raw)
        if 'crop' in d:
            x0,y0,x1,y1=d['crop'];assert 0<=x0<x1<=1 and 0<=y0<y1<=1
    for s in S.values():
        x0,y0,x1,y1=s['crop']
        for x,y,label in s['parts']:assert x0<=x<=x1 and y0<=y<=y1,(s['source'],label)
    render=json.loads((OUT/'assets/models/RENDER_PROVENANCE.json').read_text())
    render_by_file={im['file']:(r,im) for r in render for im in r.get('images',[])}
    model_checks=[]
    for c in data:
        for m in c['models']:
            basename=Path(m['image']).with_suffix('.png').name
            if basename in render_by_file:
                r,im=render_by_file[basename];assert r['id']==c['cid'];assert r['status']=='PASS_READONLY';assert r['mesh_transform_unchanged'] and r['binary_unchanged']
                model_checks.append((c['id'],r['id'],'BINARY_RENDER_OBJECT_MATCH'))
            else:
                assert c['cid'] in m.get('source_url','') or c['cid'] in basename,(c['id'],m)
                model_checks.append((c['id'],c['cid'],'EXISTING_REVIEW_PATH_MATCH'))
        for m in c.get('local_models',[]):
            r,im=render_by_file[Path(m['image']).with_suffix('.png').name]
            assert ' '.join(im['object_names'])==m['label'],m
            model_checks.append((c['id'],m['label'],'LOCAL_OBJECT_EXACT_NAME_MATCH'))
    # Original raster/mesh/transform records and canonical engineering state are
    # immutable in this revision. Check against the actual prior branch commit.
    git_check='NOT_AVAILABLE_IN_PARTIAL_LOCAL_MIRROR'
    if (ROOT/'.git').exists():
        protected=['production','docs/evidence','docs/project_control','docs/component_atlas_v001/atlas_data.json','docs/component_atlas_v001/assets/sources','docs/component_atlas_v001/assets/official','docs/component_atlas_v001/assets/models','docs/component_atlas_v001/assets/approved']
        delta=subprocess.check_output(['git','diff','--name-only',BASE,'--']+protected,cwd=ROOT,text=True)
        assert not delta,delta
        git_check='PASS_NO_PROTECTED_PATH_CHANGED'
    result=dict(status='PASS_STATIC',pages=79,entity_pages=sum(d['kind']=='实体构件族' for d in data),master_families=len({d['cid'] for d in data if d['cid']}),local_references=checked,decoded_referenced_images=len(imgs),derivatives=len(deriv),source_hashes_verified=len(originals),model_identity_checks=len(model_checks),model_identity_details=model_checks,original_engineering_state=git_check,browser=('PASS_GOOGLE_CHROME_FILE_AND_HTTP' if (OUT/'qa/CHROME_VALIDATION.json').exists() and json.loads((OUT/'qa/CHROME_VALIDATION.json').read_text()).get('status')=='PASS' else 'PENDING_SEPARATE_CHROME_RUN'),original_source_pixels='UNMODIFIED; DERIVATIVES_ARE_CROP_RESAMPLE_AND_ANNOTATION_ONLY')
    (OUT/'assets/v002/STATIC_VALIDATION.json').write_text(json.dumps(result,ensure_ascii=False,indent=2));print(json.dumps({k:v for k,v in result.items() if k!='model_identity_details'},ensure_ascii=False))
if __name__=='__main__':main()
